# Calculadora simples

def somar(a, b):
    return a + b

def subtrair(a, b):
    return a - b

def multiplicar(a, b):
    return a * b

# Demonstração de uso

a = 10
b = 5

print(f"Soma: {a} + {b} = {somar(a, b)}")
print(f"Subtração: {a} - {b} = {subtrair(a, b)}")
print(f"Multiplicação: {a} * {b} = {multiplicar(a, b)}")
